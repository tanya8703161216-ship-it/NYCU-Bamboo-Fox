def C(seed, a, b):
    # order cut endpoints consistently (lower point first, then left) so
    # interpolation between keys never flips the line
    a, b = sorted([a, b], key=lambda p: (-p[1], p[0]))
    return {"seed": list(seed), "cut": [list(a), list(b)]}

def P(seed, poly):
    return {"seed": list(seed), "poly": [list(p) for p in poly]}

